const fs=require('node:fs');
const path=require('node:path');
const esbuild=require('esbuild');
const sources=require('./browser-sources.cjs');
const target=['safari12','ios12','chrome64'];
const root=path.resolve(__dirname,'..');
function build(){
 const polyfills=esbuild.buildSync({
  stdin:{contents:[
   'core-js/es/global-this','core-js/es/array/at','core-js/es/array/flat','core-js/es/array/flat-map',
   'core-js/es/object/from-entries','core-js/es/object/has-own','core-js/es/string/match-all',
   'core-js/es/string/replace-all','core-js/modules/web.dom-collections.iterator','core-js/modules/web.dom-collections.for-each','core-js/web/queue-microtask'
  ].map(name=>`require(${JSON.stringify(name)});`).join('\n')+
   '\nwindow.epDialogPolyfill=require("dialog-polyfill");',resolveDir:root},
  bundle:true,write:false,format:'iife',minify:true,target,legalComments:'inline'
 }).outputFiles[0].text;
 const scripts=['browser-compat.js',...sources].map(name=>
  `/* ${name} */\n${fs.readFileSync(path.join(root,'public',name),'utf8')}`);
 const app=esbuild.transformSync(scripts.join('\n;\n'),{target,minifyWhitespace:true,legalComments:'inline'});
 return '/* Generated by scripts/build-browser-app.cjs. */\n'+polyfills+'\n'+app.code;
}
function write(){
 const file=path.join(root,'public/app-client.js');
 const bundle=build();
 fs.writeFileSync(file,bundle);
}
if(require.main===module)write();
module.exports={build,write};
